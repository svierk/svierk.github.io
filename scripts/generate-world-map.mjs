/**
 * Regenerates src/data/worldMap.ts - the dot-matrix world map behind the
 * Speaking section. Run with `npm run generate:map` (needs network access).
 *
 * Natural Earth land polygons (public domain) are projected with a Miller
 * cylindrical projection and rasterised onto a square grid. Every land cell
 * becomes a zero-length path segment; with `stroke-linecap: round` the browser
 * paints it as a dot, so the whole map is a single <path> of ~19 KB instead of
 * ~2000 <circle> elements.
 */
import { writeFileSync } from 'node:fs';

const SOURCE =
  'https://raw.githubusercontent.com/martynafford/natural-earth-geojson/master/110m/physical/ne_110m_land.json';

/** Poles are cropped - no talks there, and it keeps the aspect ratio usable. */
const LAT_MAX = 84;
const LAT_MIN = -56;
const WIDTH = 1000;
/**
 * Grid spacing in viewBox units; smaller means more dots and a bigger path.
 * The Speaking map crops into this grid, so it is generated finer than it is
 * drawn - the crop trims everything outside the visible window at build time.
 */
const STEP = 5;
const DOT_RADIUS = 0.95;

const millerY = (lat) => 1.25 * Math.log(Math.tan(Math.PI / 4 + 0.4 * ((lat * Math.PI) / 180)));
const SCALE = WIDTH / (2 * Math.PI);
const Y_TOP = millerY(LAT_MAX);
const HEIGHT = Math.round((Y_TOP - millerY(LAT_MIN)) * SCALE);

const project = (lon, lat) => [((lon + 180) / 360) * WIDTH, (Y_TOP - millerY(lat)) * SCALE];

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`Failed to fetch land polygons: ${response.status}`);
const geo = await response.json();

/** Flatten to a list of polygons, each an array of rings (outer ring first). */
const polygons = [];
for (const feature of geo.features) {
  const { type, coordinates } = feature.geometry;
  const parts = type === 'Polygon' ? [coordinates] : coordinates;
  for (const rings of parts) {
    polygons.push(rings.map((ring) => ring.map(([lon, lat]) => project(lon, lat))));
  }
}

/** Bounding box per polygon - cheap rejection before the ray cast. */
const boxes = polygons.map(([outer]) => {
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;
  for (const [x, y] of outer) {
    if (x < minX) minX = x;
    if (x > maxX) maxX = x;
    if (y < minY) minY = y;
    if (y > maxY) maxY = y;
  }
  return [minX, minY, maxX, maxY];
});

const inRing = (ring, px, py) => {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > py !== yj > py && px < ((xj - xi) * (py - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
};

const isLand = (px, py) => {
  for (let p = 0; p < polygons.length; p++) {
    const [minX, minY, maxX, maxY] = boxes[p];
    if (px < minX || px > maxX || py < minY || py > maxY) continue;
    const rings = polygons[p];
    if (!inRing(rings[0], px, py)) continue;
    // Skip lakes and other holes punched into the outer ring.
    if (rings.slice(1).some((ring) => inRing(ring, px, py))) continue;
    return true;
  }
  return false;
};

const dots = [];
for (let y = STEP / 2; y < HEIGHT; y += STEP) {
  for (let x = STEP / 2; x < WIDTH; x += STEP) {
    if (isLand(x, y)) dots.push(`M${Math.round(x)} ${Math.round(y)}h0`);
  }
}

const file = `// Generated by scripts/generate-world-map.mjs - do not edit by hand.
// Source: Natural Earth 1:110m land polygons (public domain).

export const mapWidth = ${WIDTH};
export const mapHeight = ${HEIGHT};
/** Radius of a single land dot, in viewBox units. */
export const dotRadius = ${DOT_RADIUS};

/**
 * Projects a coordinate pair onto the map's viewBox using the same Miller
 * cylindrical projection the land dots were rasterised with.
 */
export function project(lon: number, lat: number): { x: number; y: number } {
  const millerY = (value: number) => 1.25 * Math.log(Math.tan(Math.PI / 4 + 0.4 * ((value * Math.PI) / 180)));
  const scale = ${WIDTH} / (2 * Math.PI);
  const top = millerY(${LAT_MAX});
  return { x: ((lon + 180) / 360) * ${WIDTH}, y: (top - millerY(lat)) * scale };
}

/** ${dots.length} land dots as a single path; paint with stroke-linecap: round. */
export const landPath =
  '${dots.join('')}';
`;

writeFileSync(new URL('../src/data/worldMap.ts', import.meta.url), file);
console.log(`Wrote src/data/worldMap.ts - ${dots.length} dots, ${HEIGHT}px tall.`);
